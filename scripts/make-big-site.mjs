#!/usr/bin/env node
/**
 * Generates fake site data for testing at real-world size.
 *
 *   node scripts/make-big-site.mjs                      -> test-data/big-site.json (1,000 devices, not committed)
 *   node scripts/make-big-site.mjs --devices 40 --out test-data/sample-site.json
 *
 * The data is fictional. Never put real customer data in test-data/.
 */
import { randomUUID } from "node:crypto";
import { writeFileSync } from "node:fs";
import { resolve } from "node:path";

const args = process.argv.slice(2);
const arg = (name, fallback) => {
  const i = args.indexOf(`--${name}`);
  return i >= 0 ? args[i + 1] : fallback;
};
const deviceCount = Number(arg("devices", "1000"));
const out = resolve(arg("out", "test-data/big-site.json"));

const sizes = ["5 lb ABC", "10 lb ABC", "10 lb ABC", "20 lb ABC", "5 lb CO2", "6 L Class K"];
const makers = ["Ansul", "Pyro-Chem", "Amerex", "Badger", "Strike First", "Flag Fire"];
const areas = ["Shop", "Warehouse", "Office", "Loading dock", "Mezzanine", "Yard", "Chemical shed"];

// The first four devices match the ones in the FireGuard Pro prototype.
const named = [
  ["10 lb ABC", "Pyro-Chem", 2029, 2035, "Bleed-off truck, NH3 site"],
  ["10 lb ABC", "Ansul", 2027, 2032, "Shop spare"],
  ["10 lb ABC", "Strike First", 2027, 2033, "Ammonia tank (east site)"],
  ["5 lb ABC", "Flag Fire", 2030, 2036, "Storage, farm supply"],
];

const devices = [];
for (let i = 0; i < deviceCount; i++) {
  const n = named[i];
  const year = 2016 + (i % 10);
  devices.push({
    id: randomUUID(),
    seq: i + 1,
    discipline: "FE",
    barcode: `FG${String(100000 + i)}`,
    location: n ? n[4] : `${areas[i % areas.length]} ${Math.floor(i / areas.length) + 1}`,
    attributes: {
      size_type: n ? n[0] : sizes[i % sizes.length],
      manufacturer: n ? n[1] : makers[i % makers.length],
      serial: `SN${String(500000 + i * 7)}`,
      manufacture_year: year,
      six_year_due: n ? n[2] : year + 6,
      hydro_due: n ? n[3] : year + 12,
    },
  });
}

const data = {
  _note: "Fictional test data generated by scripts/make-big-site.mjs",
  branch: { id: randomUUID(), name: "Sample Branch", province: "SK" },
  users: [
    {
      id: randomUUID(),
      name: "Ali Technician",
      email: "ali.tech@example.com",
      role: "technician",
      certifications: ["FE", "EL", "EX", "FA"],
    },
    {
      id: randomUUID(),
      name: "Casey Coordinator",
      email: "casey.coord@example.com",
      role: "coordinator",
      certifications: [],
    },
  ],
  customer: {
    id: randomUUID(),
    softrendId: "CUST-SAMPLE-1",
    name: "Prairie Ag Supply (sample)",
    billingEmail: "accounts@example.com",
  },
  site: {
    id: randomUUID(),
    softrendId: "SITE-SAMPLE-1",
    name: "Prairie Ag Supply, Main Yard",
    address: "100 Sample Rd",
    city: "Canora",
    province: "SK",
    accessNotes: "Gate code 0000#. Call ahead.",
  },
  workOrder: {
    id: randomUUID(),
    softrendWo: "SAMPLE-0001",
    scheduledAt: "2026-12-01T15:00:00Z",
    estHours: "2.5",
    coordinatorNote: "Morning arrival only.",
  },
  woDisciplines: [{ id: randomUUID(), discipline: "FE", templateId: "FE-SK-v1" }],
  devices,
};

writeFileSync(out, `${JSON.stringify(data, null, 2)}\n`);
console.log(`Wrote ${devices.length} devices to ${out}`);
